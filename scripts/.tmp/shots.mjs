import { chromium } from '@playwright/test';
const base = process.env.BASE || 'http://localhost:4173/';
const out = '/home/claude/kuyaypet-v04-shots/';
const b = await chromium.launch({ executablePath: process.env.PW_CHROMIUM, proxy: process.env.HTTPS_PROXY ? { server: process.env.HTTPS_PROXY, bypass: 'localhost,127.0.0.1' } : undefined });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, locale: 'es-PE', serviceWorkers: 'block', ignoreHTTPSErrors: true });
const p = await ctx.newPage();
await p.goto(base); await p.evaluate(() => localStorage.clear());
await p.goto(base + '#/'); await p.waitForTimeout(1500); await p.screenshot({ path: out + 'splash.png' });
await p.getByRole('button', { name: /Adoptante/ }).click(); await p.waitForTimeout(2500); await p.screenshot({ path: out + 'descubrir.png' });
await p.goto(base + '#/mascota/p01'); await p.waitForTimeout(1500); await p.screenshot({ path: out + 'mascota-p01.png' });
await p.goto(base + '#/historias'); await p.waitForTimeout(3000); await p.screenshot({ path: out + 'historias.png' });
await p.goto(base + '#/sprints'); await p.waitForTimeout(4000); await p.screenshot({ path: out + 'sprints.png' });
await ctx.close();
const d = await b.newContext({ viewport: { width: 1440, height: 900 }, locale: 'es-PE', serviceWorkers: 'block', ignoreHTTPSErrors: true });
const q = await d.newPage();
await q.goto(base); await q.evaluate(() => localStorage.clear());
await q.goto(base + '#/'); await q.waitForTimeout(1500); await q.screenshot({ path: out + 'desktop-presenter.png' });
await q.getByRole('button', { name: /Adoptante/ }).first().click(); await q.waitForTimeout(2500); await q.screenshot({ path: out + 'desktop-presenter-deck.png' });
await b.close();
